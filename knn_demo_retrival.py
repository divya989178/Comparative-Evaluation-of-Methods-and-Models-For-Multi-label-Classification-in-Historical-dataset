import pandas as pd
import ujson as json

demo=pd.read_excel("/content/demo.xlsx")
test=pd.read_excel("/content/test.xlsx")
train=pd.read_excel("/content/train.xlsx")
val=pd.read_excel("/content/val.xlsx")

def knn_demo_retrieval(args):
    data={name:df.reset_index().rename(columns={'index':'id'}).to_dict('records') for name,df in zip(["demo","test","train","val"],[demo,test,train,val])}
    text = {split: [sample['text'] for sample in data[split]]
            for split in data}
    embed = {split: embeddings(args, text[split])
             for split in text}
    for split in ['train', 'val', 'test']:
        sim = cosine_similarity(embed[split], embed['demo'])
        scores, indices = sim.topk(k=args.topk, dim=-1)
        results = dict()
        for i in range(scores.size(0)):
            key_id = data[split][i]['id']
            context = []
            for score, j in zip(scores[i], indices[i]):
                val_id = data['demo'][j]['id']
                context.append({'id': val_id, 'score': score.item()})
            results[key_id] = context
        with open(f'{split}-knn-demo.json', 'w', encoding='utf-8') as f:
            json.dump(results, f, ensure_ascii=False, indent=2)
class Args:
  def __init__(self):
    self.topk = 5
    self.embedding_model = 'sentence-transformers/LaBSE'
    self.device = 'cuda:0'

args = Args()
knn_demo_retrieval(args)