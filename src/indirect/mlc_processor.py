import os
import ujson as json
from tqdm import tqdm
from transformers import PreTrainedTokenizer, AutoTokenizer
from datasets import Dataset, DatasetDict

def mlc_reader(tokenizer:PreTrainedTokenizer,dataset:dict,cache_name:str='',use_cache=True):
    files = {key:dataset[key] for key in dataset if key!='test'}
    tag2id = label2id
    if use_cache:
        cache_file = os.path.join('/content', f'{cache_name}.json')
        cache = json.load(open(cache_file, 'r', encoding='utf-8'))
    dataset_dict = {}
    for split, data_list in files.items():
        features = {'input_ids': [], 'id': [], 'text': [], 'labels': []}
        for sample in tqdm(data_list, desc=split):
            if 'label' not in sample:
              sample["label"]=[]
            text,label_names=sample['text'],sample["label"]
            if split=='train' and use_cache:
              domain=[]
              sample_id=str(sample["id"])
              if sample_id in cache:
                cached_data=cache[sample_id]
                if isinstance(cached_data,list) and len(cached_data)>0:
                  if isinstance(cached_data[0],dict) and 'labels' in cached_data[0]:
                    domain=cached_data[0]['labels']
              label_names=domain
              if domain is None:
                domain=[]
              label_names=domain
            input_ids = tokenizer.encode(text,truncation=True,max_length=512)
            labels=[0.0]*len(tag2id)
            for label in label_names:
              if label in tag2id:
                labels[tag2id[label]]=1.0
            if split == 'train' and use_cache and str(sample['id']) not in cache:
              labels = None
            features['input_ids'].append(input_ids)
            features['id'].append(sample['id'])
            features['text'].append(sample['text'])
            features['labels'].append(labels)
        dataset_dict[split]=features
    return dataset_dict

class Processor:
    def __init__(self, dataset: dict, tokenizer: AutoTokenizer, cache_name: str = 'cache'):
        self.tokenizer = tokenizer
        self.dataset_name = dataset
        self.tag2id = label2id
        self.id2tag = id2label

        if cache_name is None:
            self.cache_file = None
            self.cache_name = None
            self.use_cache = False
        else:
            self.cache_file = os.path.join('/content', f'{cache_name}.json')
            self.cache_name = cache_name
            self.use_cache = True
            if not os.path.exists(self.cache_file):
              cache = dict()
              json.dump(cache, open(self.cache_file, 'w'))
        print(f'Loading dataset {dataset}')

        data = mlc_reader(tokenizer, self.dataset_name, self.cache_name,
                          self.use_cache)

        self.tokenized_datasets = DatasetDict({
            split: Dataset.from_dict(data[split])
            for split in data
            })
        print('Finish loading dataset')

    def update_cache(self, records: dict):
      cache = json.load(open(self.cache_file, 'r', encoding='utf-8'))
      cache.update(records)
      json.dump(cache, open(self.cache_file, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

    def reload(self):
        print('Reloading dataset')
        data = mlc_reader(self.tokenizer, self.dataset_name, self.cache_name, self.use_cache) #changed this from features to tokenized_datasets
        self.tokenized_datasets = DatasetDict({
          split: Dataset.from_dict(data[split])
          for split in data})
        print('Finish reloading dataset')

    def get_id2tag(self):
        return self.id2tag

    def get_tag2id(self):
        return self.tag2id

    def get_features(self, split: str):
        if split in self.tokenized_datasets:
            #if split == 'train':
            return self.tokenized_datasets[split]
        else:
            raise ValueError(f"Split '{split}' not found in dataset")